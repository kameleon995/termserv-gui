"""Render system config files from the port table.

Everything here is pure: Config in, text out. Writing and reloading lives in apply.py.
"""

from __future__ import annotations

from .model import Config

HEADER = "# Generated by termserv from /etc/termserv/ports.yaml. Do not edit by hand.\n"
ATTACH_HELPER = "/usr/local/lib/termserv/serial-attach"
BANNER_PATH = "/etc/termserv/banner"


def conserver_cf(cfg: Config, released: set[int] | frozenset[int] = frozenset()) -> str:
    """conserver config. Released ports are left out, so conserver lets go of the device."""
    s = cfg.settings
    out = [
        HEADER,
        "default full {\n    rw *;\n}\n",
        "default * {\n"
        f"    logfile {s.log_dir}/&.log;\n"
        "    timestamp 1hab;\n"
        "    master localhost;\n"
        f"    port {s.conserver_port};\n"
        "    include full;\n"
        "}\n",
    ]
    ports = cfg.enabled_ports()
    if not ports:
        out.append("# No ports enabled.\n")
    for p in ports:
        if p.number in released:
            out.append(f"# {p.console} released for local use (termservctl grab {p.number})\n")
            continue
        lines = [
            f"console {p.console} {{",
            "    type device;",
            f"    device {p.device_path()};",
            f"    baud {p.baud};",
            f"    parity {p.parity};",
        ]
        if p.name:
            lines.append(f"    aliases {p.name};")
        if p.ondemand:
            lines.append("    options ondemand;")
        lines.append("}")
        out.append("\n".join(lines) + "\n")
    if not any(p.number not in released for p in ports):
        # conserver refuses to run with zero consoles; keep a harmless placeholder
        # (on demand, so it never runs anything until someone attaches to it).
        out.append("console termserv-idle {\n    type exec;\n    exec /bin/true;\n    options ondemand;\n}\n")
    # Only local clients (the SSH attach helper, the UI) may talk to conserver,
    # and they are trusted because sshd already authenticated the user.
    # "limited *" takes away the escape commands that would let an SSH user out of
    # their port: Ctrl-E c | (run a command on this server, i.e. a shell),
    # Ctrl-E c ; (switch to another console, bypassing per-port groups) and
    # Ctrl-E c z (suspend the client).
    out.append("access * {\n    trusted 127.0.0.1;\n    limited *;\n}\n")
    return "\n".join(out)


def sshd_config(cfg: Config, host_keys: list[str] | None = None, banner_path: str = BANNER_PATH) -> str:
    """sshd config for the dedicated serial sshd instance.

    Returns an empty string when no port is enabled: sshd would otherwise fall back
    to port 22 and clash with the admin sshd, so apply.py stops the service instead.
    """
    ports = cfg.enabled_ports()
    if not ports:
        return ""
    s = cfg.settings
    host_keys = host_keys or [
        "/etc/ssh/ssh_host_ed25519_key",
        "/etc/ssh/ssh_host_ecdsa_key",
        "/etc/ssh/ssh_host_rsa_key",
    ]
    out = [HEADER]
    out += [f"Port {cfg.ssh_port(p)}" for p in ports]
    out.append("")
    out += [f"HostKey {k}" for k in host_keys]
    out += [
        "",
        "PidFile /run/termserv-sshd.pid",
        f"AllowGroups {s.ssh_group}",
        "PermitRootLogin no",
        "PubkeyAuthentication yes",
        "PasswordAuthentication yes",
        "KbdInteractiveAuthentication no",
        "UsePAM yes",
        "DisableForwarding yes",
        "PermitTunnel no",
        "PermitUserRC no",
        "PermitTTY yes",
        "PrintMotd no",
        "PrintLastLog no",
        f"Banner {banner_path}",
        "ClientAliveInterval 60",
        "ClientAliveCountMax 3",
        "LogLevel VERBOSE",
        "# Safety net: no shell, ever. Each port's Match block names its console.",
        "ForceCommand /bin/false",
        "",
    ]
    for p in ports:
        out.append(f"# Port {p.number}{' (' + p.name + ')' if p.name else ''}")
        out.append(f"Match LocalPort {cfg.ssh_port(p)}")
        if p.groups:
            out.append(f"    AllowGroups {' '.join(p.groups)}")
        out.append(f"    ForceCommand {ATTACH_HELPER} {p.console} {s.conserver_port}")
        out.append("")
    return "\n".join(out)


def banner(cfg: Config) -> str:
    """Pre-login text sshd shows before asking for a password.

    ssh silently sends the local username when none is given, and the server
    cannot tell, so the best we can do is say so up front. The file is static,
    so it shows a placeholder rather than an address that may change (DHCP).
    """
    ports = cfg.enabled_ports()
    first = cfg.ssh_port(ports[0]) if ports else cfg.settings.base_port + 1
    return (
        "\r\n termserv serial console server\r\n"
        "\r\n"
        " Log in with your account name on this server:\r\n"
        f"     ssh <username>@<address> -p {first}\r\n"
        "\r\n"
        " Without <username>@, ssh uses the name of your local user\r\n"
        " and the login will fail.\r\n"
        "\r\n"
    )


def udev_rules(cfg: Config) -> str:
    """Stable /dev/portN names for USB-serial adapters, keyed on USB socket path."""
    out = [HEADER]
    for p in sorted(cfg.ports, key=lambda p: p.number):
        if p.usb_path:
            out.append(
                f'SUBSYSTEM=="tty", ENV{{ID_PATH}}=="{p.usb_path}", '
                f'SYMLINK+="port{p.number}", GROUP="dialout", MODE="0660"'
            )
    return "\n".join(out) + "\n"
