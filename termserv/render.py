"""Render system config files from the port table.

Everything here is pure: Config in, text out. Writing and reloading lives in apply.py.
"""

from __future__ import annotations

from .model import Config

HEADER = "# Generated by termserv from /etc/termserv/ports.yaml. Do not edit by hand.\n"
ATTACH_HELPER = "/usr/local/lib/termserv/serial-attach"


def conserver_cf(cfg: Config) -> str:
    s = cfg.settings
    out = [
        HEADER,
        "default full {\n    rw *;\n}\n",
        "default * {\n"
        f"    logfile {s.log_dir}/&.log;\n"
        "    timestamp 1hab;\n"
        "    master localhost;\n"
        f"    port {s.conserver_port};\n"
        "    include full;\n"
        "}\n",
    ]
    ports = cfg.enabled_ports()
    if not ports:
        out.append("# No ports enabled.\n")
    for p in ports:
        lines = [
            f"console {p.console} {{",
            "    type device;",
            f"    device {p.device_path()};",
            f"    baud {p.baud};",
            f"    parity {p.parity};",
        ]
        if p.name:
            lines.append(f"    aliases {p.name};")
        lines.append("}")
        out.append("\n".join(lines) + "\n")
    # Only local clients (the SSH attach helper, the UI) may talk to conserver,
    # and they are trusted because sshd already authenticated the user.
    out.append("access * {\n    trusted 127.0.0.1;\n}\n")
    return "\n".join(out)


def sshd_config(cfg: Config, host_keys: list[str] | None = None) -> str:
    """sshd config for the dedicated serial sshd instance.

    Returns an empty string when no port is enabled: sshd would otherwise fall back
    to port 22 and clash with the admin sshd, so apply.py stops the service instead.
    """
    ports = cfg.enabled_ports()
    if not ports:
        return ""
    s = cfg.settings
    host_keys = host_keys or [
        "/etc/ssh/ssh_host_ed25519_key",
        "/etc/ssh/ssh_host_ecdsa_key",
        "/etc/ssh/ssh_host_rsa_key",
    ]
    out = [HEADER]
    out += [f"Port {cfg.ssh_port(p)}" for p in ports]
    out.append("")
    out += [f"HostKey {k}" for k in host_keys]
    out += [
        "",
        "PidFile /run/termserv-sshd.pid",
        f"AllowGroups {s.ssh_group}",
        "PermitRootLogin no",
        "PubkeyAuthentication yes",
        "PasswordAuthentication yes",
        "KbdInteractiveAuthentication no",
        "UsePAM yes",
        "DisableForwarding yes",
        "PermitTunnel no",
        "PermitUserRC no",
        "PermitTTY yes",
        "PrintMotd no",
        "PrintLastLog no",
        "ClientAliveInterval 60",
        "ClientAliveCountMax 3",
        "LogLevel VERBOSE",
        "# Safety net: no shell, ever. Each port's Match block names its console.",
        "ForceCommand /bin/false",
        "",
    ]
    for p in ports:
        out.append(f"# Port {p.number}{' (' + p.name + ')' if p.name else ''}")
        out.append(f"Match LocalPort {cfg.ssh_port(p)}")
        if p.groups:
            out.append(f"    AllowGroups {' '.join(p.groups)}")
        out.append(f"    ForceCommand {ATTACH_HELPER} {p.console} {s.conserver_port}")
        out.append("")
    return "\n".join(out)


def udev_rules(cfg: Config) -> str:
    """Stable /dev/portN names for USB-serial adapters, keyed on USB socket path."""
    out = [HEADER]
    for p in sorted(cfg.ports, key=lambda p: p.number):
        if p.usb_path:
            out.append(
                f'SUBSYSTEM=="tty", ENV{{ID_PATH}}=="{p.usb_path}", '
                f'SYMLINK+="port{p.number}", GROUP="dialout", MODE="0660"'
            )
    return "\n".join(out) + "\n"
