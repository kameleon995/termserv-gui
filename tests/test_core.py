import shutil

import pytest
import yaml

from termserv import apply as applymod
from termserv import cli, model, render


def make_cfg():
    return model.Config(
        ports=[
            model.Port(number=2, name="switch1", baud=9600, groups=["lab"]),
            model.Port(number=1, name="router1", usb_path="platform-3610000.usb-usb-0:1.2:1.0"),
            model.Port(number=3, enabled=False),
        ]
    )


def test_ssh_port_mapping():
    cfg = make_cfg()
    assert [cfg.ssh_port(p) for p in cfg.enabled_ports()] == [2001, 2002]


def test_roundtrip(tmp_path):
    f = tmp_path / "ports.yaml"
    model.save(make_cfg(), f)
    data = yaml.safe_load(f.read_text())
    assert [p["number"] for p in data["ports"]] == [1, 2, 3]
    assert "device" not in data["ports"][0]  # empty optional fields dropped
    assert model.load(f).to_dict() == make_cfg().to_dict()


def test_missing_file_is_empty(tmp_path):
    assert model.load(tmp_path / "nope.yaml").ports == []


@pytest.mark.parametrize(
    "port,msg",
    [
        (model.Port(number=0), "number must be"),
        (model.Port(number=1, baud=12345), "baud"),
        (model.Port(number=1, parity="mark"), "parity"),
        (model.Port(number=1, device="/etc/passwd"), "under /dev/"),
        (model.Port(number=1, device="/dev/x; rm"), "invalid characters"),
        (model.Port(number=1, name="bad name"), "name"),
        (model.Port(number=1, groups=["Bad Group"]), "group"),
        (model.Port(number=1, usb_path='x" RUN+="/bin/sh'), "usb_path"),
    ],
)
def test_validation_rejects(port, msg):
    with pytest.raises(model.ConfigError, match=msg):
        model.Config(ports=[port]).validate()


def test_duplicates_rejected():
    cfg = model.Config(ports=[model.Port(number=1, name="a"), model.Port(number=1, name="a")])
    with pytest.raises(model.ConfigError) as e:
        cfg.validate()
    assert "duplicate port number" in str(e.value) and "duplicate name" in str(e.value)


def test_unknown_field_rejected():
    with pytest.raises(model.ConfigError, match="unknown field"):
        model.Config.from_dict({"ports": [{"number": 1, "speed": 9600}]})


def test_conserver_cf():
    text = render.conserver_cf(make_cfg())
    assert "console port1 {" in text and "console port2 {" in text
    assert "console port3" not in text  # disabled
    assert "device /dev/port1;" in text
    assert "baud 9600;" in text
    assert "aliases router1;" in text
    assert "trusted 127.0.0.1;" in text


def test_sshd_config():
    text = render.sshd_config(make_cfg())
    lines = text.splitlines()
    assert "Port 2001" in lines and "Port 2002" in lines and "Port 2003" not in lines
    assert "ForceCommand /bin/false" in lines
    assert "Match LocalPort 2002" in lines
    i = lines.index("Match LocalPort 2002")
    assert lines[i + 1] == "    AllowGroups lab"
    assert lines[i + 2] == "    ForceCommand /usr/local/lib/termserv/serial-attach port2 782"
    assert "DisableForwarding yes" in lines


def test_sshd_config_empty_when_no_ports():
    # sshd with no Port line would listen on 22 and clash with the admin sshd
    assert render.sshd_config(model.Config()) == ""


def test_udev_rules():
    text = render.udev_rules(make_cfg())
    assert 'ENV{ID_PATH}=="platform-3610000.usb-usb-0:1.2:1.0", SYMLINK+="port1"' in text
    assert "port2" not in text  # no usb_path


@pytest.mark.skipif(not (shutil.which("sshd") and shutil.which("conserver")), reason="needs sshd and conserver")
def test_generated_config_passes_daemon_syntax_checks(tmp_path):
    # sshd -t needs readable host keys; generate throwaway ones
    import subprocess

    key = tmp_path / "hostkey"
    subprocess.run(["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-f", str(key)], check=True)
    cfg = make_cfg()
    sc = tmp_path / "sshd_config"
    sc.write_text(render.sshd_config(cfg, host_keys=[str(key)]))
    subprocess.run(["/usr/sbin/sshd", "-t", "-f", str(sc)], check=True)
    cf = tmp_path / "conserver.cf"
    cf.write_text(render.conserver_cf(cfg))
    subprocess.run(["conserver", "-S", "-C", str(cf)], check=True, capture_output=True)


def test_apply_writes_files_without_reload(tmp_path, monkeypatch):
    monkeypatch.setattr(applymod, "check", lambda cfg: {
        "conserver_cf": render.conserver_cf(cfg),
        "sshd_config": render.sshd_config(cfg),
        "udev_rules": render.udev_rules(cfg),
    })
    paths = applymod.Paths(
        conserver_cf=tmp_path / "conserver.cf",
        sshd_config=tmp_path / "sshd_config",
        udev_rules=tmp_path / "99-termserv.rules",
    )
    log = applymod.apply(make_cfg(), paths=paths, reload=False)
    assert len(log) == 3
    assert paths.sshd_config.read_text().startswith("# Generated by termserv")


def test_cli_set_list_remove(tmp_path, capsys):
    f = str(tmp_path / "ports.yaml")
    assert cli.main(["-f", f, "set", "1", "--name", "r1", "--baud", "9600"]) == 0
    assert cli.main(["-f", f, "set", "2", "--groups", "lab,ops", "--disable"]) == 0
    capsys.readouterr()
    assert cli.main(["-f", f, "list"]) == 0
    out = capsys.readouterr().out
    assert "2001" in out and "r1" in out and "9600" in out
    cfg = model.load(f)
    assert cfg.port(2).groups == ["lab", "ops"] and not cfg.port(2).enabled
    assert cli.main(["-f", f, "set", "1", "--baud", "1234"]) == 2  # rejected, file unchanged
    assert model.load(f).port(1).baud == 9600
    assert cli.main(["-f", f, "remove", "2"]) == 0
    assert model.load(f).port(2) is None


